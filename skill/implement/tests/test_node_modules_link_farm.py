def test_shared_resolution_reports_stale_through_a_whole_directory_symlink(
    tmp_path,
):
    """A whole-directory symlink resolves the shared package to the main copy."""
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)
    (wt / "node_modules").symlink_to(main / "node_modules", target_is_directory=True)

    resolution = implement._shared_package_resolution(str(wt), str(main))

    assert resolution["applicable"] is True
    assert resolution["ok"] is False
    assert resolution["package"] == SHARED_NAME
    assert _real(Path(resolution["resolved_root"])) == _real(
        main / "packages" / "shared"
    )
    assert _real(Path(resolution["expected_root"])) == _real(
        wt / "packages" / "shared"
    )
    assert _real(Path(resolution["stale_dist"])) == _real(
        main / "packages" / "shared" / "dist"
    )


