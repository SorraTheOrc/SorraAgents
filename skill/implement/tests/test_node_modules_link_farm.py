def _clean_stash_result() -> dict:
    """An empty, non-orphaned stash inspection result."""
    return {
        "total_stashes": 0,
        "orphaned_stashes": [],
        "matched_stashes": [],
        "has_orphaned": False,
        "warning": None,
    }


