def test_repo_without_a_workspace_shared_package_keeps_the_directory_symlink(
    tmp_path,
):
    """Degradation: no workspace shared package keeps today's behaviour.

    Repos that do not consume a workspace package by path get the plain
    whole-directory symlink (best-effort, non-fatal), so the change is
    confined to worktree setups that need the farm.
    """
    main = _make_main_checkout(tmp_path, workspace_shared=False)
    wt = _make_worktree(main, tmp_path)

    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True

    wt_nm = wt / "node_modules"
    assert wt_nm.is_symlink()
    assert _real(wt_nm) == _real(main / "node_modules")
    assert _real(wt_nm / "left-pad") == _real(main / "node_modules" / "left-pad")


def test_link_step_does_not_write_into_the_main_checkout(tmp_path):
    """The link step never mutates the shared ``node_modules`` install.

    Writes through the farm would corrupt every concurrent worktree and the
    live checkout's dependencies (the constraint the whole epic is built on):
    the main checkout's tree is byte-for-byte unchanged, ``@worklog/shared``
    included, and its ``dist`` is never rebuilt or rewritten.
    """
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)
    main_nm = main / "node_modules"
    before_view = _farm_view(main_nm)
    before_stat = {
        name: os.lstat(main_nm / name).st_ino for name in os.listdir(main_nm)
    }
    shared_dist = main / "packages" / "shared" / "dist" / "index.js"
    before_dist = shared_dist.read_text(encoding="utf-8")

    implement._ensure_node_modules_symlink(str(wt), str(main))

    assert _farm_view(main_nm) == before_view
    assert {
        name: os.lstat(main_nm / name).st_ino for name in os.listdir(main_nm)
    } == before_stat
    assert shared_dist.read_text(encoding="utf-8") == before_dist


