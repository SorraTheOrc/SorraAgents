#: The workspace package consumed by path in the reference case (ContextHub).
SHARED_NAME = "@worklog/shared"


# ---------------------------------------------------------------------------
# Fixtures: a synthetic workspace checkout + a plain worktree directory
# ---------------------------------------------------------------------------


def _make_main_checkout(root: Path, *, workspace_shared: bool = True) -> Path:
    """Create a main-checkout fixture with a realistic ``node_modules`` tree.

    Mirrors the layout that produces the stale resolution: the shared package
    lives at ``packages/shared`` (``src`` + gitignored ``dist``) and
    ``node_modules/@worklog/shared`` is a **relative** symlink back to it,
    exactly as a real workspace install leaves it.
    """
    main = root / "main"
    nm = main / "node_modules"
    (nm / "left-pad").mkdir(parents=True)
    (nm / "left-pad" / "index.js").write_text(
        "module.exports = 'left-pad';\n", encoding="utf-8"
    )
    (nm / "typescript" / "bin").mkdir(parents=True)
    (nm / "typescript" / "bin" / "tsc").write_text("#!/bin/sh\n", encoding="utf-8")
    (nm / "@types" / "node").mkdir(parents=True)
    (nm / "@types" / "node" / "package.json").write_text(
        json.dumps({"name": "@types/node"}) + "\n", encoding="utf-8"
    )
    (nm / ".bin").mkdir()
    (nm / ".bin" / "tsc").symlink_to("../typescript/bin/tsc")

    (main / "package.json").write_text(
        json.dumps(
            {
                "name": "fixture-workspace",
                "private": True,
                "workspaces": ["packages/*"],
            }
        )
        + "\n",
        encoding="utf-8",
    )

    if workspace_shared:
        shared = main / "packages" / "shared"
        (shared / "src").mkdir(parents=True)
        (shared / "dist").mkdir(parents=True)
        (shared / "package.json").write_text(
            json.dumps({"name": SHARED_NAME, "main": "./dist/index.js"}) + "\n",
            encoding="utf-8",
        )
        (shared / "src" / "index.js").write_text(
            "export const VERSION = 'main-src';\n", encoding="utf-8"
        )
        (shared / "dist" / "index.js").write_text(
            "exports.VERSION = 'main-stale-dist';\n", encoding="utf-8"
        )
        (nm / "@worklog").mkdir()
        # The relative link a workspace install creates (``@worklog/shared``
        # -> ``../../packages/shared``): resolving it from a worktree yields
        # the MAIN checkout's package.
        (nm / "@worklog" / "shared").symlink_to("../../packages/shared")

    return main


def _make_worktree(main: Path, root: Path) -> Path:
    """Create the worktree fixture: branch content, no ``node_modules``.

    A linked worktree never contains gitignored ``node_modules``, which is
    exactly why ``implement.py start`` links it in.
    """
    wt = root / "wt"
    wt.mkdir()
    (wt / "package.json").write_text(
        (main / "package.json").read_text(encoding="utf-8"), encoding="utf-8"
    )
    if (main / "packages").is_dir():
        shutil.copytree(main / "packages", wt / "packages")
    return wt


def _real(path: Path) -> Path:
    """The resolved real path of *path* (what an import would land on)."""
    return Path(os.path.realpath(str(path)))


def _farm_view(nm: Path) -> dict[str, str]:
    """A stable one/two-level view of a ``node_modules`` tree.

    Entries are ``name -> readlink target`` for links and ``"<dir>"`` for real
    directories; scope directories (``@scope``) are expanded one level so a
    re-materialised ``@scope/pkg`` link is visible to the comparison.
    """
    view: dict[str, str] = {}
    for name in sorted(os.listdir(nm)):
        entry = nm / name
        if entry.is_symlink():
            view[name] = os.readlink(str(entry))
            continue
        view[name] = "<dir>"
        if name.startswith("@") and entry.is_dir():
            for inner in sorted(os.listdir(entry)):
                scoped = entry / inner
                target = os.readlink(str(scoped)) if scoped.is_symlink() else "<dir>"
                view[f"{name}/{inner}"] = target
    return view


