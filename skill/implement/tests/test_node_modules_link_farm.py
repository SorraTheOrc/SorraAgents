"""Worktree-local ``node_modules`` link farm — test-first slice.

Parent epic **SA-0MVMZBJGT00718ZO** ("implement.py worktrees resolve
``@worklog/shared`` to the main checkout's stale ``dist``"). This module is
the **F1 test-first slice** (SA-0MVPI3JSP009BZ55); the behaviour it pins is
implemented by the sibling slices:

- **SA-0MVPI400Y001FOM1** — replace the whole-directory ``node_modules``
  symlink with an idempotent, refreshable link farm whose workspace-package
  entries resolve to the **worktree's** own ``packages/*``;
- **SA-0MVPI41SR008JYXL** — hard-fail ``finish`` on stale resolution (its unit
  and negative-path tests live in ``test_stale_shared_resolution.py``).

Why this matters
----------------
``implement.py start`` used to symlink ``<worktree>/node_modules`` to the
**main checkout's** ``node_modules``. The main checkout's
``node_modules/@worklog/shared`` is itself a relative symlink to
``../../packages/shared``, so every ``@worklog/shared`` import in a worktree
resolved to the main checkout's (gitignored, arbitrarily old)
``packages/shared/dist``: a change under ``packages/shared/src/**`` was
invisible to the build/test gate — a false red (WL-0MVK6S4HM005GBCO) and,
equally possible, a false green.

Tracer-bullet convention
------------------------
The behaviour was pinned red first (the F1 test-first slice); the link farm
below is the implementation that turns those expectations green. Two tests are
**unmarked companions** that pass against the legacy whole-directory symlink
and must stay green after the farm lands:

- ``test_repo_without_a_workspace_shared_package_keeps_the_directory_symlink``
  — the documented degradation path;
- ``test_link_step_does_not_write_into_the_main_checkout`` — the link step
  never mutates the shared install.

They keep the red baselines unambiguous: a failing test can only be failing
on the behaviour under test, never on a broken fixture or a missing helper.

Fixtures are throwaway directories under ``tmp_path`` (a synthetic workspace
checkout plus a plain worktree directory) — never the live checkout. No test
installs anything: ``npm install`` inside a worktree stays forbidden, so the
farm must be materialised purely by linking.
"""

