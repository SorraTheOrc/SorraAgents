# AC3 — idempotent and refreshable
# ---------------------------------------------------------------------------


def test_link_step_is_idempotent(tmp_path):
    """Re-running the link step creates no duplicates and rewires nothing."""
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)

    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True
    wt_nm = wt / "node_modules"
    assert wt_nm.is_dir() and not wt_nm.is_symlink()
    assert _real(wt_nm / SHARED_NAME) == _real(wt / "packages" / "shared")
    first = _farm_view(wt_nm)

    implement._ensure_node_modules_symlink(str(wt), str(main))

    assert _farm_view(wt_nm) == first
    # Still a real farm, and the workspace override still points at the
    # worktree (a lazy re-run must not rewire it to the main checkout).
    assert wt_nm.is_dir() and not wt_nm.is_symlink()
    assert _real(wt_nm / SHARED_NAME) == _real(wt / "packages" / "shared")
    assert sorted(os.listdir(wt_nm)) == sorted(os.listdir(main / "node_modules"))


def test_link_step_materialises_new_dependencies(tmp_path):
    """A dependency added to the main checkout appears on the next link step."""
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)
    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True
    wt_nm = wt / "node_modules"
    assert "newdep" not in os.listdir(wt_nm)

    (main / "node_modules" / "newdep").mkdir()
    (main / "node_modules" / "newdep" / "index.js").write_text(
        "module.exports = 'newdep';\n", encoding="utf-8"
    )

    implement._ensure_node_modules_symlink(str(wt), str(main))

    assert (wt_nm / "newdep").is_symlink()
    assert _real(wt_nm / "newdep") == _real(main / "node_modules" / "newdep")
    # Existing entries survive the refresh.
    assert (wt_nm / "left-pad").is_symlink()
    assert _real(wt_nm / "left-pad") == _real(main / "node_modules" / "left-pad")


