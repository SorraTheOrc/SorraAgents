def test_link_step_creates_a_real_directory_farm(tmp_path):
    """``<worktree>/node_modules`` is a real directory of per-entry links.

    One symlink per main-checkout entry, ``.bin`` linked as a whole directory,
    and the farm's entry set is exactly the main checkout's entry set — no
    whole-directory symlink anywhere at the root.
    """
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)

    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True

    wt_nm = wt / "node_modules"
    main_nm = main / "node_modules"
    assert wt_nm.is_dir(), f"{wt_nm} is not a directory"
    assert not wt_nm.is_symlink(), "node_modules is still a whole-directory symlink"

    # An ordinary dependency is a per-entry link into the main checkout.
    assert (wt_nm / "left-pad").is_symlink()
    assert _real(wt_nm / "left-pad") == _real(main_nm / "left-pad")

    # ``.bin`` is linked as a whole directory, not farmed entry by entry.
    assert (wt_nm / ".bin").is_symlink()
    assert _real(wt_nm / ".bin") == _real(main_nm / ".bin")

    # The farm mirrors exactly the main checkout's entry set.
    assert sorted(os.listdir(wt_nm)) == sorted(os.listdir(main_nm))


def test_scoped_packages_are_materialised_per_package(tmp_path):
    """Scopes are real directories with one link per scoped package."""
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)

    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True

    wt_scope = wt / "node_modules" / "@types"
    main_scope = main / "node_modules" / "@types"
    assert wt_scope.is_dir()
    assert not wt_scope.is_symlink(), "the scope must not be a link to the main scope"
    assert (wt_scope / "node").is_symlink()
    assert _real(wt_scope / "node") == _real(main_scope / "node")


