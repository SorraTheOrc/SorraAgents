def test_workspace_package_resolves_to_the_worktree_copy(tmp_path):
    """``@worklog/shared`` resolves inside the worktree, not the main checkout.

    This is the whole point of the farm: an import of the workspace package
    from the worktree must land on ``<worktree>/packages/shared`` (whose
    ``src`` the item changed) rather than the main checkout's stale copy.
    """
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)

    assert implement._ensure_node_modules_symlink(str(wt), str(main)) is True

    resolved = _real(wt / "node_modules" / SHARED_NAME)
    assert resolved == _real(wt / "packages" / "shared")
    assert resolved != _real(main / "packages" / "shared")
    # The scope holding the override is a real directory, not the main scope.
    assert (wt / "node_modules" / "@worklog").is_dir()
    assert not (wt / "node_modules" / "@worklog").is_symlink()


def test_existing_whole_directory_symlink_is_replaced_by_a_farm(tmp_path):
    """A worktree created by the old code is migrated on the next link step.

    ``implement.py start`` may resume a worktree whose ``node_modules`` is
    still the whole-directory symlink; the link step must replace it rather
    than skip (the documented refresh path is re-running ``start``).
    """
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)
    (wt / "node_modules").symlink_to(main / "node_modules", target_is_directory=True)
    assert _real(wt / "node_modules" / SHARED_NAME) == _real(main / "packages" / "shared")

    implement._ensure_node_modules_symlink(str(wt), str(main))

    wt_nm = wt / "node_modules"
    assert not wt_nm.is_symlink()
    assert _real(wt_nm / SHARED_NAME) == _real(wt / "packages" / "shared")


