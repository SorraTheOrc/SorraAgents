def test_start_report_includes_shared_resolution_on_fresh_start_and_refresh(
    tmp_path,
):
    """AC2: the ``start`` JSON report carries the resolution result on both paths.

    A fresh ``start`` materialises the farm and reports a worktree-local
    resolution; the resume/refresh path re-runs the same step, keeps the farm
    intact and reports the same result.
    """
    main = _make_main_checkout(tmp_path)
    wt = _make_worktree(main, tmp_path)

    for resumed in (False, True):
        with _mocked_phase_start(main, wt, resumed=resumed):
            report = implement.phase_start("SA-TEST", json_output=True)

        assert report["success"] is True, report
        assert report["shared_resolution_ok"] is True
        resolution = report["shared_resolution"]
        assert resolution["applicable"] is True
        assert _real(Path(resolution["resolved_root"])) == _real(
            wt / "packages" / "shared"
        )
        assert report["steps"]["node_modules"]["shared_resolution"] == resolution

    # The refresh did not degrade the farm back to a whole-directory symlink.
    wt_nm = wt / "node_modules"
    assert wt_nm.is_dir() and not wt_nm.is_symlink()
    assert _real(wt_nm / SHARED_NAME) == _real(wt / "packages" / "shared")
