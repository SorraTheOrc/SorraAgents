class TestSymlinkHelper:
    def test_creates_symlink_when_main_has_node_modules(self, tmp_path):
        """Main checkout has node_modules, worktree lacks it → symlink created."""
        repo, wt = _make_repo(tmp_path, with_node_modules=True)
        _git_worktree_add(repo, wt)
        assert not (wt / "node_modules").exists()

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            result = mod._ensure_node_modules_symlink({str(wt)!r}, {str(repo)!r})
            print(f"RESULT:{{result}}")
            print(f"ISLINK:{{os.path.islink(os.path.join({str(wt)!r}, 'node_modules'))}}")
            print(f"RESOLVED:{{os.path.realpath(os.path.join({str(wt)!r}, 'node_modules'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "True")
        _assert_line_in(proc, "ISLINK:", "True")
        expected_target = str((repo / "node_modules").resolve())
        assert expected_target in proc.stdout, (
            f"symlink must point at the main checkout node_modules\nstdout:\n{proc.stdout}"
        )

    def test_does_not_replace_existing_worktree_node_modules(self, tmp_path):
        """Existing worktree node_modules dir is preserved, never replaced."""
        repo, wt = _make_repo(tmp_path, with_node_modules=True)
        _git_worktree_add(repo, wt)
        existing = wt / "node_modules"
        existing.mkdir()
        (existing / "own.txt").write_text("worktree-specific")

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            result = mod._ensure_node_modules_symlink({str(wt)!r}, {str(repo)!r})
            print(f"RESULT:{{result}}")
            print(f"ISLINK:{{os.path.islink(os.path.join({str(wt)!r}, 'node_modules'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "False")
        _assert_line_in(proc, "ISLINK:", "False")
        assert existing.is_dir(), "existing node_modules dir must survive"
        assert (existing / "own.txt").read_text() == "worktree-specific"

    def test_skips_when_main_lacks_node_modules(self, tmp_path):
        """No node_modules in main checkout → skip silently, no crash."""
        repo, wt = _make_repo(tmp_path, with_node_modules=False)
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            result = mod._ensure_node_modules_symlink({str(wt)!r}, {str(repo)!r})
            print(f"RESULT:{{result}}")
            print(f"EXISTS:{{os.path.lexists(os.path.join({str(wt)!r}, 'node_modules'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "False")
        _assert_line_in(proc, "EXISTS:", "False")

    def test_skips_when_repo_root_unknown(self, tmp_path):
        """repo_root=None (not in a git repo) → skip silently, no crash."""
        repo, wt = _make_repo(tmp_path, with_node_modules=True)
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            result = mod._ensure_node_modules_symlink({str(wt)!r}, None)
            print(f"RESULT:{{result}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "False")

    def test_symlink_failure_logged_not_fatal(self, tmp_path):
        """os.symlink raising (e.g. permissions) → logged, no exception."""
        repo, wt = _make_repo(tmp_path, with_node_modules=True)
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            import os as _os
            def _boom(*a, **k):
                raise OSError("permission denied")
            _os.symlink = _boom
            result = mod._ensure_node_modules_symlink({str(wt)!r}, {str(repo)!r})
            print(f"RESULT:{{result}}")
            print(f"EXISTS:{{_os.path.lexists(_os.path.join({str(wt)!r}, 'node_modules'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "False")
        _assert_line_in(proc, "EXISTS:", "False")
        assert "permission denied" in proc.stderr, (
            f"failure must be logged to stderr\nstdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
        )

    def test_symlink_uses_directory_target_flag(self, tmp_path):
        """os.symlink must be called with target_is_directory=True (Windows)."""
        repo, wt = _make_repo(tmp_path, with_node_modules=True)
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            import os as _os
            calls = []
            def _record(*a, **k):
                calls.append((a, k))
            _os.symlink = _record
            result = mod._ensure_node_modules_symlink({str(wt)!r}, {str(repo)!r})
            print(f"RESULT:{{result}}")
            print(f"CALLS:{{calls!r}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        _assert_line_in(proc, "RESULT:", "True")
        assert "target_is_directory" in proc.stdout, (
            f"os.symlink must pass target_is_directory\nstdout:\n{proc.stdout}"
        )


