"""Tests for the implement.py node_modules auto-symlink (SA-0MSGS763C006SM1B).

Contract (per work item ACs):

- AC: `implement.py start` creates a `<worktree>/node_modules` symlink to the
  main checkout's node_modules when the main checkout has one and the
  worktree lacks one.
- AC: an existing worktree node_modules (dir or symlink) is never
  overwritten/replaced by start.
- AC: no symlink is created when the main checkout lacks node_modules
  (and no crash occurs).
- AC: symlink failure (e.g. permissions / unsupported platform) does not
  abort start; it is logged and start continues.
- AC: `implement/SKILL.md` documents the symlink and the "no npm-install
  in worktrees" caveat.

Background: git worktrees do not include gitignored directories, so tests
that spawn a real subprocess via an absolute worktree-relative path (e.g.
`node <worktree>/node_modules/.bin/tsx` in CLI e2e tests) fail with
MODULE_NOT_FOUND. Symlinking the main checkout's node_modules fixes this.
"""

import json
import subprocess
import sys
import textwrap
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
_IMPLEMENT_PY = _REPO_ROOT / "skill" / "implement" / "scripts" / "implement.py"
_SKILL_MD = _REPO_ROOT / "skill" / "implement" / "SKILL.md"

_FAKE_WORK_ITEM_ID = "SA-TEST123"


