class TestStructural:
    SOURCE = _IMPLEMENT_PY.read_text() if _IMPLEMENT_PY.exists() else ""

    def test_phase_start_calls_symlink_after_worktree_add(self):
        """The symlink helper must run after the worktree is created."""
        assert self.SOURCE, f"implement.py not found at {_IMPLEMENT_PY}"
        add_idx = self.SOURCE.index("git_worktree_add(branch, wt_path, parent_branch)")
        call_idx = self.SOURCE.index("_ensure_node_modules_symlink(abs_wt_path")
        assert add_idx != -1
        assert call_idx > add_idx, (
            "node_modules symlink helper must be called AFTER the worktree is created"
        )

    def test_helper_defined(self):
        """The symlink helper function must exist."""
        assert self.SOURCE
        assert "def _ensure_node_modules_symlink(" in self.SOURCE


