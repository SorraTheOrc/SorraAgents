"""Tests for the implement.py *nested* node_modules auto-symlink.

Contract (OSL-0MUFG3PJA00379CT / AC1-AC7):

- AC1: the repository-root symlink behaviour in
  ``_ensure_node_modules_symlink`` is preserved (existing
  ``tests/test_implement_node_modules_symlink.py`` covers it unchanged).
- AC2: ``implement.py start`` symlinks every nested ``node_modules`` from the
  main checkout into the worktree at the same relative path when the worktree
  lacks one — e.g.
  ``<wt>/.pi/packages/<pkg>/node_modules -> <main>/.pi/packages/<pkg>/node_modules``.
- AC3: an existing entry (real directory or symlink) at a candidate path inside
  the worktree is never overwritten.
- AC4: no symlink is created when the candidate's parent package directory does
  not exist in the worktree (no fabricated directories / branch shadowing).
- AC5: discovery prunes ``.git`` and ``.worklog``, never descends into a
  ``node_modules`` directory, and does not follow symlinked directories.
- AC6: a per-candidate symlink failure is logged at ``WARNING`` and does not
  abort; remaining candidates are still linked.
- AC7: a Node module-resolution check from the worktree package directory
  (skipped when ``node`` is unavailable).

Background: git worktrees do not include gitignored directories. On checkouts
whose only dependencies live in a nested package (pi packages, npm
workspaces, monorepo apps) the worktree gets no ``node_modules`` at all, so
``pi``/``tsx`` fail with ``Cannot find module``.
"""

