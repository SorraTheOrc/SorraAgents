class TestNestedSymlinkHelper:
    def test_creates_nested_symlink_when_main_has_nested_node_modules(self, tmp_path):
        """AC2: nested node_modules linked at the same relative path."""
        repo, wt = _make_repo(tmp_path, packages=(_NESTED_PKG,))
        _git_worktree_add(repo, wt)
        assert not (wt / _NESTED_PKG / "node_modules").exists()

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            link = os.path.join({str(wt)!r}, {_NESTED_PKG!r}, "node_modules")
            print(f"CREATED:{{created}}")
            print(f"ISLINK:{{os.path.islink(link)}}")
            print(f"RESOLVED:{{os.path.realpath(link)}}")
            print(f"CONTENT:{{open(os.path.join(link, 'nested-dep.txt')).read()}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "1"
        assert _value(proc, "ISLINK:") == "True"
        expected = str((repo / _NESTED_PKG / "node_modules").resolve())
        assert _value(proc, "RESOLVED:") == expected
        assert _value(proc, "CONTENT:") == f"nested-deps-{_NESTED_PKG}"

    def test_does_not_replace_existing_entry(self, tmp_path):
        """AC3: an existing worktree entry is preserved, never replaced."""
        repo, wt = _make_repo(tmp_path, packages=(_NESTED_PKG,))
        _git_worktree_add(repo, wt)
        existing = wt / _NESTED_PKG / "node_modules"
        existing.mkdir()
        (existing / "own.txt").write_text("worktree-specific")

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            link = os.path.join({str(wt)!r}, {_NESTED_PKG!r}, "node_modules")
            print(f"CREATED:{{created}}")
            print(f"ISLINK:{{os.path.islink(link)}}")
            print(f"OWN:{{open(os.path.join(link, 'own.txt')).read()}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "0"
        assert _value(proc, "ISLINK:") == "False"
        assert _value(proc, "OWN:") == "worktree-specific"
        assert existing.is_dir()

    def test_does_not_fabricate_package_directory(self, tmp_path):
        """AC4: no link when the parent package is absent from the worktree."""
        repo, wt = _make_repo(tmp_path)
        _git_worktree_add(repo, wt)
        # Package exists only in the main checkout (as if removed by the branch).
        nm = repo / "pkg-a" / "node_modules"
        nm.mkdir(parents=True)
        (nm / "dep.txt").write_text("pkg-a-deps")
        assert not (wt / "pkg-a").exists()

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            print(f"CREATED:{{created}}")
            print(f"WT_PKG_EXISTS:{{os.path.lexists(os.path.join({str(wt)!r}, 'pkg-a'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "0"
        assert _value(proc, "WT_PKG_EXISTS:") == "False"
        assert not (wt / "pkg-a").exists()

    def test_bounded_discovery_prunes_heavy_and_dependency_trees(self, tmp_path):
        """AC5: no links under ``.worklog`` or inside a ``node_modules`` tree."""
        repo, wt = _make_repo(tmp_path)
        _git_worktree_add(repo, wt)

        # Main checkout: nested node_modules inside a dependency tree, and a
        # node_modules under .worklog (both must be pruned).
        inner = repo / "node_modules" / "inner" / "node_modules"
        inner.mkdir(parents=True)
        (inner / "dep.txt").write_text("inner-deps")
        worklog_nm = repo / ".worklog" / "worktrees" / "x" / "node_modules"
        worklog_nm.mkdir(parents=True)
        (worklog_nm / "dep.txt").write_text("worklog-deps")

        # Worktree parent dirs exist, so an unbounded walk WOULD link these.
        (wt / "node_modules" / "inner").mkdir(parents=True)
        (wt / ".worklog" / "worktrees" / "x").mkdir(parents=True)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            inner_link = os.path.join(
                {str(wt)!r}, "node_modules", "inner", "node_modules")
            worklog_link = os.path.join(
                {str(wt)!r}, ".worklog", "worktrees", "x", "node_modules")
            print(f"CREATED:{{created}}")
            print(f"INNER_LINK:{{os.path.lexists(inner_link)}}")
            print(f"WORKLOG_LINK:{{os.path.lexists(worklog_link)}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "0"
        assert _value(proc, "INNER_LINK:") == "False"
        assert _value(proc, "WORKLOG_LINK:") == "False"

    def test_symlink_failure_logged_not_fatal(self, tmp_path):
        """AC6: one failing candidate is logged; others are still linked."""
        repo, wt = _make_repo(
            tmp_path, packages=("pkg-a", "pkg-b")
        )
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            _real_symlink = os.symlink

            def _flaky(src, dst, *a, **k):
                if "pkg-a" in str(dst):
                    raise OSError("permission denied")
                return _real_symlink(src, dst, *a, **k)

            os.symlink = _flaky
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            print(f"CREATED:{{created}}")
            print(f"A_LINK:{{os.path.lexists(os.path.join({str(wt)!r}, 'pkg-a', 'node_modules'))}}")
            print(f"B_LINK:{{os.path.lexists(os.path.join({str(wt)!r}, 'pkg-b', 'node_modules'))}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "1"
        assert _value(proc, "A_LINK:") == "False"
        assert _value(proc, "B_LINK:") == "True"
        assert "permission denied" in proc.stderr

    def test_skips_when_repo_root_unknown(self, tmp_path):
        """repo_root=None → no-op, no crash."""
        repo, wt = _make_repo(tmp_path, packages=("pkg-a",))
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks({str(wt)!r}, None)
            print(f"CREATED:{{created}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "0"

    def test_node_resolution_from_worktree_package(self, tmp_path):
        """AC7: Node resolves a nested dependency through the worktree symlink."""
        if shutil.which("node") is None:
            import pytest

            pytest.skip("node is not available")

        dep = "test-resolvable-dep"
        repo, wt = _make_repo(tmp_path, packages=("pkg",))
        dep_dir = repo / "pkg" / "node_modules" / dep
        dep_dir.mkdir(parents=True)
        (dep_dir / "package.json").write_text(
            json.dumps({"name": dep, "main": "index.js"})
        )
        (dep_dir / "index.js").write_text("module.exports = 42;\n")
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            print(f"CREATED:{{created}}")
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == "1"

        resolved = subprocess.run(
            ["node", "-e", f"process.stdout.write(require.resolve({dep!r}))"],
            cwd=str(wt / "pkg"),
            capture_output=True,
            text=True,
            check=False,
        )
        assert resolved.returncode == 0, resolved.stderr
        # Node resolves through the symlink to the main checkout, but only if
        # the worktree's node_modules symlink exists (MODULE_NOT_FOUND
        # otherwise).
        assert f"node_modules/{dep}" in resolved.stdout.replace("\\", "/")
        assert resolved.stdout.endswith("index.js")

    def test_multiple_nested_packages_all_linked(self, tmp_path):
        """AC2: every discovered nested package gets its own link."""
        packages = ("packages/a", "packages/b", "apps/c")
        repo, wt = _make_repo(tmp_path, packages=packages)
        _git_worktree_add(repo, wt)

        runner = _module_loader(repo) + textwrap.dedent(f"""\
            created = mod._ensure_nested_node_modules_symlinks(
                {str(wt)!r}, {str(repo)!r})
            print(f"CREATED:{{created}}")
            for pkg in {packages!r}:
                print(f"LINK:{{pkg}}:" + str(os.path.islink(
                    os.path.join({str(wt)!r}, pkg, "node_modules"))))
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        assert _value(proc, "CREATED:") == str(len(packages))
        for pkg in packages:
            assert _value(proc, f"LINK:{pkg}:") == "True"


