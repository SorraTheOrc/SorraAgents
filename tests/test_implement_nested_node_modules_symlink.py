class TestPhaseStartIntegration:
    def test_phase_start_creates_nested_symlink(self, tmp_path):
        """Full start flow: nested node_modules linked, no root node_modules."""
        repo, wt = _make_repo(tmp_path, packages=(_NESTED_PKG,))
        runner = _module_loader(repo) + textwrap.dedent(f"""\
            mod.is_code_freeze_active = lambda: False

            class _FakeLifecycle:
                @staticmethod
                def update_status(*a, **k):
                    return None

            mod.StatusLifecycle = _FakeLifecycle
            mod.git_status = lambda cwd=None: ""
            mod.git_has_dirty_files = lambda status_output=None: False
            mod.wl_show = lambda i: {{"id": i, "title": "Test item"}}
            mod.wl_add_comment = lambda *a, **k: True

            result = mod.phase_start(
                "SA-TEST123",
                json_output=True,
                worktree_path_override={str(wt)!r},
            )
            print("RESULT_JSON:" + json.dumps(result))
            print("NESTED_LINK:" + str(os.path.islink(os.path.join(
                {str(wt)!r}, {_NESTED_PKG!r}, "node_modules"))))
        """)
        proc = _run_in_subprocess(tmp_path, runner)
        assert proc.returncode == 0, proc.stderr
        result = json.loads(_value(proc, "RESULT_JSON:"))
        assert result["success"] is True, result
        assert _value(proc, "NESTED_LINK:") == "True"
        assert (wt / _NESTED_PKG / "node_modules" / "nested-dep.txt").read_text() == (
            f"nested-deps-{_NESTED_PKG}"
        )


