def _git(repo: Path, *args: str) -> None:
    subprocess.run(
        ["git", *args], cwd=str(repo), check=True, capture_output=True
    )


def _make_repo(
    tmp_path: Path,
    *,
    root_node_modules: bool = False,
    packages: tuple[str, ...] = (),
) -> tuple[Path, Path]:
    """Create a minimal git repo with a ``dev`` branch.

    ``packages`` are committed package directories (so the worktree inherits the
    parent directory); each gets a gitignored nested ``node_modules`` in the
    main checkout only.

    Returns:
        ``(repo_root, worktree_dir)`` — worktree_dir does not exist yet.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init")
    _git(repo, "config", "user.email", "test@test.com")
    _git(repo, "config", "user.name", "Test")
    (repo / ".gitignore").write_text("node_modules/\n")
    (repo / "README.md").write_text("# Test")

    if root_node_modules:
        nm = repo / "node_modules"
        nm.mkdir()
        (nm / "root-dep.txt").write_text("root-deps")

    for pkg in packages:
        pkg_dir = repo / pkg
        pkg_dir.mkdir(parents=True)
        (pkg_dir / "package.json").write_text(
            json.dumps({"name": pkg.replace("/", "-")})
        )
        nm = pkg_dir / "node_modules"
        nm.mkdir()
        (nm / "nested-dep.txt").write_text(f"nested-deps-{pkg}")

    _git(repo, "add", "-A")
    _git(repo, "commit", "-m", "Initial commit")
    _git(repo, "branch", "dev")

    worktree_dir = (tmp_path / "wt").resolve()
    return repo, worktree_dir


def _git_worktree_add(repo: Path, worktree_dir: Path) -> None:
    """Create a real git worktree inside the test repo (branch ``wl-test``)."""
    _git(
        repo,
        "worktree",
        "add",
        "--track",
        "-b",
        "wl-test",
        str(worktree_dir),
        "dev",
    )


def _module_loader(repo: Path) -> str:
    """Python preamble that loads implement.py as ``mod`` with cwd=repo."""
    return textwrap.dedent(f"""\
        import json
        import os
        import sys
        sys.path.insert(0, {str(_REPO_ROOT)!r})
        os.chdir({str(repo)!r})
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "implement_under_test", {str(_IMPLEMENT_PY)!r},
        )
        mod = importlib.util.module_from_spec(spec)
        mod.__package__ = "implement_scripts"
        sys.modules["implement_under_test"] = mod
        spec.loader.exec_module(mod)
    """)


def _run_in_subprocess(tmp_path: Path, runner_source: str) -> subprocess.CompletedProcess:
    runner_path = tmp_path / "_nested_test_runner.py"
    runner_path.write_text(runner_source)
    return subprocess.run(  # noqa: PLW1510
        [sys.executable, str(runner_path)],
        cwd=str(tmp_path),
        capture_output=True,
        text=True,
        timeout=120,
    )


def _value(proc: subprocess.CompletedProcess, prefix: str) -> str:
    for line in proc.stdout.splitlines():
        if line.startswith(prefix):
            return line[len(prefix):]
    raise AssertionError(
        f"No {prefix} line in stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )


