"""Guard-fires proofs for both live-repo mutation guard entry points (F2, SA-0MUG30HV8004HV94).

Covers:

- AC3 — the repo-root-conftest guard (``skill/shared/live_repo_guard.py``)
  fires on a mutation and names the offending test, run as a real nested
  pytest session inside a ``tmp_path`` repository;
- AC4 — the ``run_tests.py`` snapshot guard (F4) exits non-zero when the
  configured suite command mutates a ref;
- AC5 — no false positives: churn in an unrelated repository, a no-op run, and
  agent-worktree churn (branch advance, plus registration/removal mid-run
  including the ``--track`` branch config) do not trip the guard
  (SA-0MUINEW6X0034C65).

No live checkout is mutated to obtain any proof; every mutation happens in a
``tmp_path`` repository created through ``shared.git_sandbox``.
"""
from __future__ import annotations

import json
import subprocess
import sys
import textwrap
from pathlib import Path

from shared import git_sandbox as gs

REPO_ROOT = Path(__file__).resolve().parents[1]
GUARD_MODULE = REPO_ROOT / "skill" / "shared" / "live_repo_guard.py"
RUN_TESTS = REPO_ROOT / "skill" / "test" / "scripts" / "run_tests.py"
MARKER_ENV = "LIVE_REPO_GUARD_ACTIVE"


def _child_env() -> dict[str, str]:
    """Environment for a nested run: no repo overrides, no guard marker."""
    env = gs.sanitized_git_env()
    env.pop(MARKER_ENV, None)
    return env


def _init_guard_repo(base: Path, name: str = "victim") -> Path:
    """Create a committed repo with the conventional Python ignores.

    The initial commit gives the default branch a valid object so fixtures can
    create branches; the ``.gitignore`` mirrors a real repo (``__pycache__`` and
    ``.pytest_cache`` are generated by the nested pytest run and must not be
    mistaken for a mutation).
    """
    repo = gs.init_repo(base / name)
    (repo / ".gitignore").write_text(
        "__pycache__/\n*.pyc\n.pytest_cache/\n.worklog/\n", encoding="utf-8"
    )
    (repo / "README.md").write_text("fixture\n", encoding="utf-8")
    gs.commit_all(repo, "init")
    return repo


def _write_guard_conftest(repo: Path) -> None:
    """Write a conftest that arms the shared guard for *repo*."""
    (repo / "conftest.py").write_text(
        textwrap.dedent(
            f"""
            import importlib.util
            from pathlib import Path

            _GUARD = Path({str(GUARD_MODULE)!r})
            _spec = importlib.util.spec_from_file_location("_live_repo_guard", _GUARD)
            _module = importlib.util.module_from_spec(_spec)
            _spec.loader.exec_module(_module)


            def pytest_configure(config):
                _module.register(config, root=Path(__file__).resolve().parent)
            """
        ).strip()
        + "\n",
        encoding="utf-8",
    )


def _run_nested_pytest(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *args],
        cwd=str(repo),
        env=_child_env(),
        capture_output=True,
        text=True,
        timeout=180,
        check=False,
    )


# ---------------------------------------------------------------------------
# AC3 — conftest entry point
# ---------------------------------------------------------------------------


class TestConftestGuardFires:
    def test_mutating_test_is_failed_and_named(self, tmp_path):
        repo = _init_guard_repo(tmp_path)
        _write_guard_conftest(repo)
        (repo / "test_mutator.py").write_text(
            "import subprocess\n"
            "from pathlib import Path\n\n"
            "def test_creates_a_branch():\n"
            "    subprocess.run(\n"
            "        ['git', '-C', str(Path(__file__).resolve().parent),\n"
            "         'branch', 'intruder'],\n"
            "        check=True,\n"
            "    )\n",
            encoding="utf-8",
        )

        proc = _run_nested_pytest(repo)

        combined = proc.stdout + proc.stderr
        assert proc.returncode != 0, combined
        assert "live-repo mutation" in combined
        assert "test_creates_a_branch" in combined
        # The guard is real: the branch really was created.
        assert gs.run_git(repo, ["rev-parse", "--verify", "refs/heads/intruder"]).returncode == 0

    def test_config_rewrite_is_failed_and_named(self, tmp_path):
        """Config rewrites are still genuine mutations after the exclusion fix."""
        repo = _init_guard_repo(tmp_path)
        _write_guard_conftest(repo)
        (repo / "test_config_mutator.py").write_text(
            "import subprocess\n"
            "from pathlib import Path\n\n"
            "def test_rewrites_config():\n"
            "    subprocess.run(['git', '-C', str(Path(__file__).resolve().parent),\n"
            "                    'config', '--local', 'user.name', 'intruder'], check=True)\n",
            encoding="utf-8",
        )

        proc = _run_nested_pytest(repo)

        combined = proc.stdout + proc.stderr
        assert proc.returncode != 0, combined
        assert "live-repo mutation" in combined
        assert "user.name" in combined


