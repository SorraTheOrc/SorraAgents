class TestRunTestsGuardFires:
    def test_configured_command_mutating_a_ref_fails_the_run(self, tmp_path):
        repo = _init_guard_repo(tmp_path)
        (repo / ".pi").mkdir()
        (repo / ".pi" / "test-config.json").write_text(
            json.dumps({"suiteCommands": ["bash mutate.sh"]}), encoding="utf-8"
        )
        (repo / "mutate.sh").write_text(
            "#!/bin/sh\ngit branch intruder\n", encoding="utf-8"
        )
        (repo / "mutate.sh").chmod(0o755)
        (repo / "tests").mkdir()
        (repo / "tests" / "test_noop.py").write_text(
            "def test_ok():\n    assert True\n", encoding="utf-8"
        )

        proc = subprocess.run(
            [
                sys.executable,
                str(RUN_TESTS),
                "--project-root",
                str(repo),
                "--scope",
                "full",
                "--json",
            ],
            cwd=str(repo),
            env=_child_env(),
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
        )

        combined = proc.stdout + proc.stderr
        assert proc.returncode != 0, combined
        assert "live-repo mutation" in combined
        assert "refs/heads/intruder" in combined

    def test_clean_configured_suite_passes(self, tmp_path):
        repo = _init_guard_repo(tmp_path, "clean")
        (repo / ".pi").mkdir()
        (repo / ".pi" / "test-config.json").write_text(
            json.dumps({"suiteCommands": ["bash noop.sh"]}), encoding="utf-8"
        )
        (repo / "noop.sh").write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        (repo / "noop.sh").chmod(0o755)

        proc = subprocess.run(
            [
                sys.executable,
                str(RUN_TESTS),
                "--project-root",
                str(repo),
                "--scope",
                "full",
                "--json",
            ],
            cwd=str(repo),
            env=_child_env(),
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
        )

        assert proc.returncode == 0, proc.stdout + proc.stderr


